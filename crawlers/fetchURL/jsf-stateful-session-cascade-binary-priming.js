// Anchors with no inner text and no id, so they stay invisible to a parser
// reading the same HTML for data.
function andamio(urls) {
  return '<div id="enlaces">' +
         urls.map((u) => `<a href="${esc(u)}"></a>`).join('') + '</div>';
}

function respuestaSoloEnlaces(canonicalURL, urls) {
  const r = simpleResponse({
    canonicalURL, mimeType: 'text/html',
    responseBody: '<html><body>' + andamio(urls) + '</body></html>',
  });
  r.doNotSave = true;              // exists only to produce links
  return r;
}

async function nivelSemilla({ canonicalURL, headers }) {
  const p = params(canonicalURL);
  const r = await situarValidado(p.tipoDoc, p.tipoNombre, 0, ROWS, headers);
  const { n, fuente } = totalDe(r.xml);

  if (!n) {
    if (r.filas.length) throw new Error('hay filas pero no se ha leido el total');
    return [respuestaSoloEnlaces(canonicalURL, [])];
  }

  let paginas = Math.ceil(n / ROWS);
  if (paginas > MAX_PAGINAS) {
    console.error(`AVISO: ${paginas} paginas (total=${n}); recorto a ${MAX_PAGINAS}`);
    paginas = MAX_PAGINAS;
  }

  const urls = [];
  for (let i = 0; i < paginas; i++) urls.push(paginaURL(p, i * ROWS));
  console.log(`${VERSION} | semilla ${p.tipoNombre}: total=${n} (via ${fuente}) paginas=${urls.length}`);

  return [respuestaSoloEnlaces(canonicalURL, urls)];
}

async function nivelPagina({ canonicalURL, headers }) {
  const p     = params(canonicalURL);
  const first = parseInt(p.first, 10) || 0;
  const rows  = parseInt(p.rows, 10) || ROWS;

  const r = await situarValidado(p.tipoDoc, p.tipoNombre, first, rows, headers);

  // No table at all is a real failure: throw so it is logged and retried.
  if (!r.tabla) throw new Error(`sin tabla en ${p.tipoNombre} first=${first}`);

  // Table present and empty is the END OF THE LIST, normal when the total is
  // unreliable. It must not count as an error.
  if (!r.filas.length) {
    console.log(`${VERSION} | pagina ${p.tipoNombre} first=${first}: sin filas`);
    return [respuestaSoloEnlaces(canonicalURL, [])];
  }

  // One POST per row to resolve its stable id, so the LISTING parser can see
  // it too. Without this the two parsers cannot merge on a stable key.
  let vs = r.vs;
  const filas = [];
  for (const f of r.filas) {
    const id = await resolverId(BASE, seleccionarForm(p.tipoDoc, f.fila, vs), headers, ZONA);
    if (!id) { console.error(`sin id para fila ${f.fila}, salto`); continue; }
    f.id = id;
    f.clave = `${BASE}?id_documento=${id}`;   // the merge key, built ONCE here
    filas.push(f);
  }
  if (!filas.length) throw new Error(`0 ids resueltos en first=${first}`);

  const urls = filas.map((f) => documentoURL(p, first, f));
  console.log(`${VERSION} | pagina ${p.tipoNombre} first=${first}: ${filas.length} filas ` +
              `ids ${filas[0].id}..${filas[filas.length - 1].id}`);

  return [simpleResponse({
    canonicalURL, mimeType: 'text/html',
    responseBody: '<html><body>' + tablaNormalizada(filas) + andamio(urls) + '</body></html>',
  })];
}

async function nivelDocumento({ canonicalURL, headers }) {
  const p     = params(canonicalURL);
  const first = parseInt(p.first, 10) || 0;
  const rows  = parseInt(p.rows, 10) || ROWS;
  const fila  = parseInt(p.fila, 10);
  const clave = p.doc || '';
  if (!clave || isNaN(fila)) return [];

  const idEsperado = p.id || '';
  const r = await situarValidado(p.tipoDoc, null, first, rows, headers);

  const esperada = r.filas.filter((f) => f.fila === fila)[0];
  if (!esperada) throw new Error(`la fila ${fila} no esta en first=${first}`);
  if (p.cod && esperada.codigo !== p.cod) {
    throw new Error(`la fila ${fila} es "${esperada.codigo}" y se esperaba "${p.cod}"`);
  }

  const id = await resolverId(BASE, seleccionarForm(p.tipoDoc, fila, r.vs), headers, ZONA);
  if (!id) throw new Error(`sin id en el header Location (${clave})`);

  // Identity checked BEFORE spending the download requests: if the list has
  // shifted, this binary is not this record's.
  if (idEsperado && id !== idEsperado) {
    throw new Error(`la fila ${fila} resuelve a id=${id} y la URI dice ${idEsperado}`);
  }

  // The detail GET creates a NEW view: the list's ViewState is invalid here.
  const detHtml = await decode(await get(`${BASE}?id_documento=${id}`, headers));
  const vsDet = vsHtml(detHtml);
  if (!vsDet) throw new Error(`sin ViewState en el detalle (id=${id})`);

  const ajax = await decode(await post(cargaInicialForm(vsDet), headers));
  if (!/partial-response/i.test(ajax) || /<error/i.test(ajax)) {
    throw new Error(`ajax de carga no valido (id=${id}): ${ajax.slice(0, 150).replace(/\s+/g, ' ')}`);
  }

  const dl  = await get(PDF, headers);
  const buf = await dl.buffer();

  // The "not found" page is served with HTTP 200, so the status tells you
  // nothing. Validate magic bytes AND a minimum size.
  const esPdf = buf && buf.length > 1000 && buf.slice(0, 5).toString('latin1') === '%PDF-';
  if (!esPdf) {
    throw new Error(`descarga no-PDF (id=${id}) ct=${dl.headers.get('content-type')} ` +
                    `bytes=${buf ? buf.length : 0} head="${buf ? buf.slice(0, 60).toString('latin1') : ''}"`);
  }

  console.log(`${VERSION} | OK binario id=${id} ${buf.length} b`);
  return [simpleResponse({ canonicalURL, mimeType: 'application/pdf', responseBody: buf })];
}

// Router: most specific path first. Canonicals from earlier designs are
// discarded explicitly so they do not fall through to defaultFetchURL.
async function fetchURL(args) {
  const u = args.canonicalURL;
  if (/https?:.*https?:/i.test(u)) return [];
  if (/[?&]listadoCES=/.test(u))   return [];

  if (/\/documento_oficial\.pdf\?/.test(u)) return nivelDocumento(args);
  if (/\/lista\.html\?/.test(u))            return nivelPagina(args);
  if (/\/inicio\.html\?tipoDoc=/.test(u))   return nivelSemilla(args);

  return defaultFetchURL(args);
}
