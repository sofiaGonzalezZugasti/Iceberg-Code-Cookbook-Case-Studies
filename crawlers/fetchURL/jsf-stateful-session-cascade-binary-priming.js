// ============================================================================
// WHEN TO USE THIS
// A JSF/PrimeFaces site where navigation state lives in the server session, not
// in the URL: search is a POST, pagination is a POST, and the binary endpoint
// returns whatever the session last selected.
//
// HOW IT WORKS
// Three levels, one queue item per unit of work. A seed does setup + search and
// emits page URLs; a page paginates and emits one URL per record; a record URL
// rebuilds the session from scratch, selects its row, fires the on-load ajax
// that puts the document in the session, and GETs the binary.
//
// WARNINGS / GOTCHAS
// - Component ids (j_idt38, j_idt47, j_idt132) are generated by JSF and
//   renumber on any redeploy. Re-capture payloads from F12 > Network.
// - One cookie jar per container: concurrent calls share a jsessionid and
//   trample each other's server state. Parallelism must stay at 1 unless you
//   manage the cookie by hand with plain fetch.
// - Every record URL must be a RECIPE, not an identifier: type, offset, rows
//   and row, because it runs hours later in another container. Never put
//   Date.now() in a canonical.
// - Throw on real failures. `return []` means "no content, and that's correct",
//   so a catch-all turns a broken crawl into a FINISHED job with no errors.
// - Stamp a version string in the first log line of the hook. If the stamp is
//   not in the log you are not running what you think you are running.
// - Measure the per-call time limit instead of assuming it.
// ============================================================================

const VERSION = 'jsf-cascade v1';
const ROWS        = 10;
const MAX_PAGINAS = 2000;

const AJAX_SOURCE  = 'j_idt47';
const AJAX_EXECUTE = 'j_idt47';
const AJAX_RENDER  = '@none';

function params(u) { return querystring.parse((u.split('?')[1] || '')); }
function fd(pairs) { const f = new FormData(); pairs.forEach(([k, v]) => f.append(k, v)); return f; }

function esc(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function vsHtml(h) { return cheerio.load(h)('input[name="jakarta.faces.ViewState"]').val() || null; }

function vsPartial(x) {
  let m = x.match(/<update id="[^"]*ViewState[^"]*"><!\[CDATA\[([\s\S]*?)\]\]><\/update>/i);
  if (m) return m[1];
  m = x.match(/name="jakarta\.faces\.ViewState"[^>]*value="([^"]+)"/);
  return m ? m[1] : null;
}

// Verified on this source that the ]]> markers close each <update>, so the
// non-greedy match is correct. With nested CDATA use the </update> delimiter.
function cdata(x, frag) {
  const m = x.match(new RegExp('id="[^"]*' + frag + '[^"]*"><!\\[CDATA\\[([\\s\\S]*?)\\]\\]>'));
  return m ? m[1] : '';
}

// The header count ("N results found") can lag a previous search when the
// session is shared. The widget's rowCount is rendered with the rows.
function totalDe(xml) {
  let m = xml.match(/rowCount\s*:\s*(\d+)/);
  if (m) return { n: +m[1], fuente: 'rowCount' };
  m = xml.match(/Se han encontrado\s+([0-9]+)\s+documento/i);
  if (m) return { n: +m[1], fuente: 'texto' };
  return { n: 0, fuente: 'ninguna' };
}

// ---------------------------------------------------------------------------
// pagination
//
// skipChildren + encodeFeature are MANDATORY: with them the server returns only
// the requested offset's rows; without them it re-renders the whole DataTable
// AND resets the offset to 0, so every page silently returns the first one.
// The price is a loose run of <tr> with no <table>, which an HTML parser
// discards -- hence comoTabla() below.
// ---------------------------------------------------------------------------
function paginaForm(first, rows, vs) {
  return fd([
    ['jakarta.faces.partial.ajax', 'true'],
    ['jakarta.faces.source', 'tablaResultados'],
    ['jakarta.faces.partial.execute', 'tablaResultados'],
    ['jakarta.faces.partial.render', 'tablaResultados'],
    ['tablaResultados', 'tablaResultados'],
    ['tablaResultados_pagination', 'true'],
    ['tablaResultados_first', String(first)],
    ['tablaResultados_rows', String(rows)],
    ['tablaResultados_skipChildren', 'true'],
    ['tablaResultados_encodeFeature', 'true'],
    ['rfm', 'rfm'], ['txtPalabraClave', ''],
    ['jakarta.faces.ViewState', vs],
  ]);
}

function comoTabla(frag) {
  if (!frag) return '';
  return /<tbody|<table/i.test(frag) ? frag : '<table><tbody>' + frag + '</tbody></table>';
}

// ---------------------------------------------------------------------------
// the ajax that primes the binary endpoint
//
// A remoteCommand fired on page load does NOT carry behavior.event or
// partial.event. Copying the shape of a click event gives an empty partial
// response with no error, and the binary keeps coming back wrong.
// ---------------------------------------------------------------------------
function cargaInicialForm(vs) {
  return fd([
    ['jakarta.faces.partial.ajax', 'true'],
    ['jakarta.faces.source', AJAX_SOURCE],
    ['jakarta.faces.partial.execute', AJAX_EXECUTE],
    ['jakarta.faces.partial.render', AJAX_RENDER],
    [AJAX_SOURCE, AJAX_SOURCE],
    ['rfm', 'rfm'],
    ['jakarta.faces.ViewState', vs],
  ]);
}

// The selection POST answers with a redirect whose Location carries the entity
// id -- often the only stable identifier the source publishes.
async function resolverId(base, body, headers, zona) {
  const sel = await fetchWithCookies(base, { method: 'POST', body, headers, redirect: 'manual' }, zona);
  const loc = sel.headers.get('location') || '';
  const m = loc.match(/id_documento=(\d+)/);
  return m ? m[1] : null;
}

